/** `one` for exactly 1, `other` for everything else — the German and Spanish rule. */
const plural = (n: number, one: string, other: string): string => (n === 1 ? one : other);
/** French treats 0 and 1 as singular: "0 ligne lue", "1 ligne lue", "2 lignes lues". */
const pluralFr = (n: number, one: string, other: string): string => (n < 2 ? one : other);

